async function measureCanvas (browser, app, slice) {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
  let mockRequests = 0
  page.on('request', (r) => { if (r.url().includes('form-builder-graph.mock.json')) mockRequests++ })
  try {
    await page.goto(`${EXPLORER}/fact-explorer/${app.explorer}`, { waitUntil: 'load', timeout: 180000 })
    await page.waitForSelector('#fe-scope', { timeout: 180000 })
    await page.waitForSelector('.react-flow__node', { timeout: 180000 })

    await page.evaluate(() => {
      window.__lt = { count: 0, total: 0, max: 0 }
      new PerformanceObserver((l) => {
        for (const e of l.getEntries()) { window.__lt.count++; window.__lt.total += e.duration; window.__lt.max = Math.max(window.__lt.max, e.duration) }
      }).observe({ entryTypes: ['longtask'] })
    })

    const t0 = Date.now()
    if (slice.value) await page.selectOption('#fe-scope', slice.value)
    // Settle is "the node count stopped changing", not a load event: the canvas keeps mounting long
    // after the fetch resolves, which is the thing being measured.
    let last = -1; let stable = 0
    while (Date.now() - t0 < 180000) {
      const n = await page.evaluate(() => document.querySelectorAll('.react-flow__node').length)
      if (n === last && n > 0) { if (++stable >= 3) break } else { stable = 0 }
      last = n
      await page.waitForTimeout(300)
    }
    const settleMs = Date.now() - t0

    const counts = await page.evaluate(() => ({
      rfNodes: document.querySelectorAll('.react-flow__node').length,
      rfEdges: document.querySelectorAll('.react-flow__edge').length,
      miniMapNodes: document.querySelectorAll('.react-flow__minimap-node').length,
      animatedEdges: document.querySelectorAll('.react-flow__edge.animated').length,
      domUnderViewport: document.querySelector('.react-flow__viewport')?.querySelectorAll('*').length ?? 0,
      blockingMs: Math.round(window.__lt.total),
      longTasks: window.__lt.count
    }))

    return { settleMs, ...counts, frames: await panFrames(page), mockRequests }
  } finally {
    await page.close()
  }
}

// The headline. Drag the pane and time the frames *during* the drag: an rAF loop awaited before the
// mouse moves measures an idle canvas, which is fast on both sides and says nothing.
async function panFrames (page) {
  const box = await (await page.$('.react-flow__pane')).boundingBox()
  const cx = box.x + box.width / 2
  const cy = box.y + box.height / 2
  await page.mouse.move(cx, cy)
  await page.mouse.down()
  await page.evaluate(() => {
    window.__raf = []
    let prev = performance.now()
    const tick = () => {
      const now = performance.now()
      window.__raf.push(now - prev)
      prev = now
      if (window.__rafOn) requestAnimationFrame(tick)
    }
    window.__rafOn = true
    requestAnimationFrame(tick)
  })
  for (let i = 0; i < 30; i++) await page.mouse.move(cx - i * 18, cy - i * 9)
  await page.mouse.up()
  return page.evaluate(() => {
    window.__rafOn = false
    const a = window.__raf.slice(2).sort((x, y) => x - y)
    if (!a.length) return { n: 0, p50: 0, p95: 0, max: 0 }
    return { n: a.length, p50: Math.round(a[Math.floor(a.length * 0.5)]), p95: Math.round(a[Math.floor(a.length * 0.95)]), max: Math.round(a.at(-1)) }
  })
}

// ---- the whole plan: the generated site ---------------------------------------------------------
//
// What a browser sees on a Direct File page before any of the plan landed, and now. Both sides are
// real builds — same flags, same 774 pages — served by the same nginx binary from the same image,
// so the only differences are the ones the plan made.

// Recorded in the page rather than derived from the trace, because both of these are about the
// moment something became true of the DOM, and neither has a Performance entry.
//
//   navReadyMs      Stage 3. The nav bar renders from templates the page now carries; before, from
//                   a fetch queued behind the flow runtime's boot. This is when the bar has markup.
//   contentReadyMs  Stage 4. The baseline ships <div id="page-content-wrapper" inert> behind a
//                   display:none, and flow-runtime.js clears both at the end of its boot; after the
//                   stage the wrapper is neither. So: the first frame at which the page is both
//                   visible and interactive, which on one side is parse time and on the other is
//                   parse time plus the whole engine boot.
// A function declaration, not a const: report() is not the only thing that runs above its own
// definitions in this file — the stage dispatch does too, and a const here is in the temporal dead
// zone when stageSite() reaches for it.
function instrumentScript () {
  return `(() => {
  const P = { longTasks: 0, blockingMs: 0, navReadyMs: null, contentReadyMs: null }
  window.__perf = P
  try {
    new PerformanceObserver((l) => {
      for (const e of l.getEntries()) { P.longTasks++; P.blockingMs += Math.max(0, e.duration - 50) }
    }).observe({ entryTypes: ['longtask'] })
  } catch (e) { /* no longtask support: the counters stay 0 rather than the run failing */ }
  const deadline = performance.now() + 120000
  const tick = () => {
    if (P.navReadyMs === null && document.querySelector('taxpert-global-nav .tgn-bar')) P.navReadyMs = performance.now()
    const w = document.getElementById('page-content-wrapper')
    if (P.contentReadyMs === null && w && !w.hasAttribute('inert') && w.getClientRects().length > 0) P.contentReadyMs = performance.now()
    // Stops as soon as both are known: an rAF loop left running for the whole measurement is a
    // sixty-times-a-second tax on the thing being measured.
    if ((P.navReadyMs !== null && P.contentReadyMs !== null) || performance.now() > deadline) return
    requestAnimationFrame(tick)
  }
  requestAnimationFrame(tick)
})()`
}

async function stageSite () {
  const out = { name: 'The generated site, pre-plan vs now', findings: ['DF-3', 'DF-4', 'DF-8', 'TX-1', 'TX-2', 'DF-2', 'DF-6', 'TX-3'], apps: [] }
  const browser = await chromium.launch()
  try {
    for (const app of apps) {
      const roots = {
        before: path.join(args.baseline, 'form-builder-examples', app.dir, 'out'),
        after: path.join(ROOT, app.dir, 'out')
      }
      const missing = args.sides.filter((side) => !existsSync(roots[side]))
      if (missing.length) {
        out.apps.push({ app: app.dir, error: `no built site for "${missing.join(', ')}" (looked in ${missing.map((m) => roots[m]).join(', ')}) — run scripts/perf-baseline.sh` })
        continue
      }
      const image = await imageBehind(app)
      if (!image) { out.apps.push({ app: app.dir, error: `no running container publishing :${app.port}, and its nginx is what serves both sides` }); continue }

      const pages = pagesToMeasure(roots, app)
      console.error(`  site · ${app.dir} · image ${image} · ${pages.map((p) => p.label).join(', ')}`)
      const sides = {}
      let assets = null
      let entry = null

      for (const side of args.sides) {
        const conf = side === 'before'
          ? gitShow(ROOT, `${baselineRef(ROOT)}:${app.dir}/nginx.conf`)
          : readFileSync(path.join(ROOT, app.dir, 'nginx.conf'), 'utf8')
        const server = await startNginx(image, conf, `${app.dir}-plan-${side}`, { dir: roots[side] })
        try {
          const origin = `http://127.0.0.1:${server.port}`
          // direct-file's `/` is a meta-refresh stub; measuring it measures 517 bytes of nothing.
          entry ??= await resolveEntry(`${origin}${app.base}/`)
          assets ??= await criticalPath(server, app, origin, entry)
          const measured = {}
          for (const pg of pages) {
            console.error(`    ${side} · ${pg.label}`)
            measured[pg.label] = await loadPageDeep(browser, origin + (pg.label === 'entry' ? entry : pg.url))
          }
          sides[side] = { pages: measured, assets: await probeAssets(origin, assets) }
        } finally {
          await server.stop()
        }
      }
      out.apps.push({ app: app.dir, image, pages, sides })
    }
  } finally {
    await browser.close()
  }
  return out
}

// Three pages, and each is a different question. The entry is what a first visit costs; the
// heaviest topic page is what the flow costs at its worst; all-screens is the developer surface
// that loads the whole chrome at once. Ranked by generated size and intersected across the two
// sides, so the pair being compared is the same page on both — a page that exists on only one side
// would make the comparison a comparison of two different documents.
function pagesToMeasure (roots, app) {
  const rank = (root) => {
    const base = path.join(root, app.base.replace(/^\//, ''))
    if (!existsSync(base)) return []
    return readdirSync(base, { recursive: true, withFileTypes: true })
      .filter((d) => d.isFile() && d.name === 'index.html')
      .map((d) => {
        const abs = path.join(d.parentPath ?? d.path, d.name)
        return { url: `${app.base}/${path.relative(base, path.dirname(abs))}/`.replace(/\/+$/, '/'), size: statSize(abs) }
      })
      .filter((x) => !x.url.includes('/es/'))
      .sort((a, b) => b.size - a.size)
  }
  const after = rank(roots.after)
  const beforeUrls = new Set(rank(roots.before).map((x) => x.url))
  const common = after.filter((x) => beforeUrls.size === 0 || beforeUrls.has(x.url))
  const entry = `${app.base}/`
  const allScreens = common.find((x) => x.url.endsWith('/all-screens/'))
  const heaviest = common.find((x) => !x.url.endsWith('/all-screens/') && x.url !== entry)
  return [
    { label: 'entry', url: entry },
    heaviest && { label: 'heaviest flow page', url: heaviest.url, bytes: heaviest.size },
    allScreens && { label: 'all-screens', url: allScreens.url, bytes: allScreens.size }
  ].filter(Boolean)
}

async function loadPageDeep (browser, url) {
  const out = {}
  for (const profile of NET_PROFILES) {
    const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    await ctx.addInitScript(instrumentScript())
    const page = await ctx.newPage()
    const errors = []
    page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text().slice(0, 160)) })
    page.on('pageerror', (e) => errors.push(String(e.message).slice(0, 160)))
    const t = installNetworkTally(await ctx.newCDPSession(page), new URL(url).origin)
    if (profile.down > 0) {
      await t.cdp.send('Network.emulateNetworkConditions',
        { offline: false, latency: profile.latency, downloadThroughput: profile.down, uploadThroughput: profile.up })
    }
    const nav = await navigate(page, t, url)
    const marks = await page.evaluate(() => ({ ...window.__perf })).catch(() => ({}))
    out[profile.name] = { ...nav, ...marks, consoleErrors: errors.length, errorSample: [...new Set(errors)].slice(0, 3) }
    await ctx.close()
  }
  return out
}

