// The plan is committed in taxpert and form-builder and uncommitted here, so "before" is a different
// ref in each. The rule is mechanical and the resolved refs are printed: if the tip commit is the one
// that landed the work, the baseline is its parent; otherwise the baseline is the tip.
function baselineRef (repo) {
  try {
    const subject = execSync(repo, ['git', 'log', '-1', '--format=%s']).trim()
    return /perf|performance/i.test(subject) ? 'HEAD^' : 'HEAD'
  } catch { return 'HEAD' }
}

