// ---- Stage 1 -----------------------------------------------------------------------------------

async function stage1 () {
  const out = { name: 'Transport hygiene', findings: ['DF-3', 'DF-4', 'DF-8'], apps: [] }
  const browser = await chromium.launch()
  try {
    for (const app of apps) {
      const image = await imageBehind(app)
      if (!image) { out.apps.push({ app: app.dir, error: `no running container publishing :${app.port}` }); continue }
      console.error(`  stage 1 · ${app.dir} · image ${image}`)

      const volume = args.root === 'volume' ? await volumeBehind(app) : null
      if (args.root === 'volume' && !volume) { out.apps.push({ app: app.dir, error: `:${app.port} mounts no volume over the web root` }); continue }
      const sides = {}
      let entry = null
      let assets = null
      let sourceMap = null

      for (const side of args.sides) {
        const conf = side === 'before'
          ? gitShow(ROOT, `HEAD:${app.dir}/nginx.conf`)
          : readFileSync(path.join(ROOT, app.dir, 'nginx.conf'), 'utf8')
        const server = await startNginx(image, conf, `${app.dir}-${side}`, volume)
        try {
          const origin = `http://127.0.0.1:${server.port}`
          // Discovered from the server we are about to measure, not from the live stack: with
          // --root image and --root volume serving different builds, an entry path or an engine
          // filename read from :3008 can simply not exist in the thing under test.
          entry ??= await resolveEntry(`${origin}${app.base}/`)
          assets ??= await criticalPath(server, app, origin, entry)
          sides[side] = {
            assets: await probeAssets(origin, assets),
            page: await loadPage(browser, origin + entry)
          }
          // While a server is up, because DF-8 is about the web root that is actually being served
          // and --root volume serves one the image has no say over.
          sourceMap ??= await sourceMapCheck(app, image, server)
        } finally {
          await server.stop()
        }
      }

      out.apps.push({
        app: app.dir,
        image,
        root: args.root,
        entry,
        sides,
        // DF-8 is not a header, so the A/B above cannot see it: both sides run the same image. What
        // it is, is a file that either is or is not in the web root being served.
        sourceMap
      })
    }
  } finally {
    await browser.close()
  }
  return out
}

// The image is read off the running container rather than guessed from the directory name, because
// the compose project name is whatever directory you brought the stack up from — `taxpert-*` images
// exist for the same apps, built from taxpert's own compose.
async function imageBehind (app) {
  const { stdout } = await execFile('docker', ['ps', '--filter', `publish=${app.port}`, '--format', '{{.Image}}'])
  return stdout.split('\n').map((s) => s.trim()).filter(Boolean).find((s) => !s.endsWith('-watch')) ?? null
}

// The compose stacks mount a named volume over /usr/share/nginx/html so the watcher can rewrite the
// site without rebuilding. That volume is seeded from the image the first time it is created and
// never again, so it can be arbitrarily older than the image — which is exactly why the two roots
// are reported separately rather than averaged into one "the app".
async function volumeBehind (app) {
  const { stdout } = await execFile('docker', ['ps', '--filter', `publish=${app.port}`, '--format', '{{.Names}}'])
  const name = stdout.split('\n').map((s) => s.trim()).filter(Boolean).find((s) => !s.endsWith('-watch-1'))
  if (!name) return null
  const { stdout: mounts } = await execFile('docker', ['inspect', name, '--format', '{{json .Mounts}}'])
  return JSON.parse(mounts).find((m) => m.Destination === '/usr/share/nginx/html' && m.Type === 'volume')?.Name ?? null
}

// `mount` is one of: nothing (serve what the image baked in), {volume} (the named volume the
// running stack mounts), or {dir} (a host directory — how the `site` stage serves a web root that
// was built somewhere else entirely).
async function startNginx (image, conf, tag, mount) {
  const volume = typeof mount === 'string' ? mount : mount?.volume
  const dir = mount?.dir
  const name = `fbx-perf-${tag}-${process.pid}`
  const confPath = path.join(scratch(), `${name}.conf`)
  writeFileSync(confPath, conf)
  await execFile('docker', ['rm', '-f', name]).catch(() => {})
  // Port 0 lets the kernel choose: this runs beside the live stack, and hard-coding a port is how a
  // measurement harness becomes the reason `make up` fails.
  await execFile('docker', ['run', '-d', '--rm', '--name', name,
    '-p', '127.0.0.1:0:80', '-v', `${confPath}:/etc/nginx/conf.d/default.conf:ro`,
    ...(volume ? ['-v', `${volume}:/usr/share/nginx/html:ro`] : []),
    ...(dir ? ['-v', `${dir}:/usr/share/nginx/html:ro`] : []), image])
  const { stdout } = await execFile('docker', ['port', name, '80'])
  const port = Number(stdout.trim().split('\n')[0].split(':').pop())
  for (let i = 0; i < 100; i++) {
    const code = await curl(`http://127.0.0.1:${port}/`, ['-o', '/dev/null', '-w', '%{http_code}']).catch(() => '')
    if (code && code !== '000') break
    await sleep(100)
  }
  return { name, port, stop: () => execFile('docker', ['rm', '-f', name]).catch(() => {}) }
}

// `/` on direct-file is a meta-refresh stub, so measuring it measures 517 bytes of nothing. Follow
// the stub to the page a user actually lands on; the other three serve the real page at `/`.
async function resolveEntry (url) {
  const body = await curl(url)
  const m = body.match(/http-equiv=["']refresh["'][^>]*url=([^"'>]+)/i)
  return m ? m[1].trim() : new URL(url).pathname
}

// The engine bundle is never named in the page: it arrives four levels down an import chain, so
// there is nothing in the HTML to match on. Ask the web root what it is called instead — the version
// in the filename moves with fact-graph, and hard-coding 3.1.0 here would quietly drop the largest
// asset in the audit from the largest number in this report.
async function criticalPath (server, app, origin, entry) {
  const { stdout } = await execFile('docker', ['exec', server.name, 'sh', '-c',
    `ls /usr/share/nginx/html${app.base}/resources/vendor/fact-graph/*.js 2>/dev/null | head -1`])
  const engine = stdout.trim()
  return [
    { label: 'entry document', url: entry },
    engine && { label: 'engine bundle', url: engine.replace('/usr/share/nginx/html', '') },
    { label: 'fact dictionary', url: `${app.base}/resources/fact-dictionary.xml` },
    { label: 'flow manifest', url: `${app.base}/resources/flow-manifest.json` },
    { label: 'vendored nav template', url: `${app.base}/resources/vendor/taxpert/global-nav/templates/global-nav.html` }
  ].filter(Boolean)
}

// curl rather than fetch: undici transparently decodes gzip and drops the headers that prove it did,
// which is the one thing this probe exists to see. Without --compressed curl leaves the body encoded,
// so size_download is what actually crossed the wire.
async function probeAssets (origin, assets) {
  const rows = []
  for (const a of assets) {
    const raw = await curl(origin + a.url, ['-o', '/dev/null', '-D', '-', '-H', 'Accept-Encoding: gzip, br',
      '-w', '\n__W %{size_download} %{http_code}\n'])
    const h = Object.fromEntries(raw.split('\n')
      .filter((l) => l.includes(':'))
      .map((l) => [l.slice(0, l.indexOf(':')).trim().toLowerCase(), l.slice(l.indexOf(':') + 1).trim()]))
    const [, wire, code] = raw.match(/__W (\d+) (\d+)/) ?? []
    rows.push({
      ...a,
      status: Number(code),
      wireBytes: Number(wire),
      encoding: h['content-encoding'] ?? null,
      cacheControl: h['cache-control'] ?? null,
      etag: Boolean(h.etag)
    })
  }
  return rows
}

// One cold visit per network profile. There is deliberately no second, warm visit: Chromium's
// in-process memory cache serves a same-context revisit whatever the headers say, so a warm pass
// measures the browser rather than the change, and reports the same number for both sides.
//
// DF-4 is therefore counted, not timed — from the response headers of every subresource the page
// actually pulls. "Reusable" is what a browser will serve on a later visit without asking nginx
// first; every other same-origin response is a conditional request, and a round trip, on every
// navigation of a 758-page site.
async function loadPage (browser, url) {
  const out = {}
  for (const profile of NET_PROFILES) {
    const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
    const page = await ctx.newPage()
    const t = installNetworkTally(await ctx.newCDPSession(page), new URL(url).origin)
    if (profile.down > 0) {
      await t.cdp.send('Network.emulateNetworkConditions',
        { offline: false, latency: profile.latency, downloadThroughput: profile.down, uploadThroughput: profile.up })
    }
    out[profile.name] = await navigate(page, t, url)
    await ctx.close()
  }
  return out
}

// Groups exist because "requests on the page" is the number TX-3 moves and it is not the number
// Stage 1 moves. Attributing bytes to a group needs the URL at loadingFinished, which only carries
// a requestId — hence the map.
// Declared as a function for the reason the file keeps running into: everything below the stage
// dispatch is reached before its own const initialisers have run.
function groupNames () { return ['taxpert-js', 'taxpert-css', 'taxpert-templates', 'fgm-data', 'other'] }
function groupOf (url) {
  if (/\/vendor\/taxpert\//.test(url)) {
    if (/\/templates\/.*\.html/.test(url)) return 'taxpert-templates'
    if (/\.css(\?|$)/.test(url)) return 'taxpert-css'
    return 'taxpert-js'
  }
  if (/\/data\/.*\.json(\?|$)/.test(url)) return 'fgm-data'
  return 'other'
}

function installNetworkTally (cdp, origin) {
  const blank = () => Object.fromEntries(groupNames().map((g) => [g, { n: 0, bytes: 0 }]))
  const t = { cdp, requests: 0, fromCache: 0, bytes: 0, status: {}, cache: { reusable: 0, revalidate: 0, unset: 0, sameOrigin: 0 }, groups: blank(), urls: new Map() }
  cdp.send('Network.enable')
  cdp.on('Network.requestWillBeSent', (e) => { t.requests++; t.urls.set(e.requestId, e.request.url); t.groups[groupOf(e.request.url)].n++ })
  // Backed out again when the browser answers it from its own memory cache. Without this the group
  // counts are not "requests over the network": an audit-mode page mounts a second copy of itself
  // once the workspace boots, and on loopback that lands inside networkidle and doubles every
  // count while costing nothing on the wire — a comparison of two browsers, not of two builds.
  cdp.on('Network.requestServedFromCache', (e) => {
    t.fromCache++
    const url = t.urls.get(e.requestId)
    if (url) t.groups[groupOf(url)].n--
  })
  cdp.on('Network.loadingFinished', (e) => {
    t.bytes += e.encodedDataLength
    const url = t.urls.get(e.requestId)
    if (url) t.groups[groupOf(url)].bytes += e.encodedDataLength
  })
  cdp.on('Network.responseReceived', (e) => {
    t.status[e.response.status] = (t.status[e.response.status] ?? 0) + 1
    if (!e.response.url.startsWith(origin)) return
    t.cache.sameOrigin++
    const cc = header(e.response.headers, 'cache-control')
    if (!cc) t.cache.unset++
    else if (/immutable/i.test(cc) || Number(cc.match(/max-age=(\d+)/i)?.[1] ?? 0) >= 86400) t.cache.reusable++
    else t.cache.revalidate++
  })
  t.reset = () => { t.requests = 0; t.fromCache = 0; t.bytes = 0; t.status = {}; t.cache = { reusable: 0, revalidate: 0, unset: 0, sameOrigin: 0 }; t.groups = blank() }
  t.snapshot = () => ({ requests: t.requests, fromCache: t.fromCache, network: t.requests - t.fromCache, bytes: t.bytes, status: { ...t.status }, cache: { ...t.cache }, groups: structuredClone(t.groups) })
  return t
}

// CDP hands headers back with whatever casing the server used.
function header (headers, name) {
  return Object.entries(headers).find(([k]) => k.toLowerCase() === name)?.[1] ?? null
}

async function navigate (page, tally, url) {
  tally.reset()
  const t0 = Date.now()
  await page.goto(url, { waitUntil: 'load', timeout: 180000 })
  const loadMs = Date.now() - t0
  await page.waitForLoadState('networkidle', { timeout: 180000 }).catch(() => {})
  const settleMs = Date.now() - t0
  const nav = await page.evaluate(() => {
    const n = performance.getEntriesByType('navigation')[0]
    const fcp = performance.getEntriesByName('first-contentful-paint')[0]
    return { dcl: n ? Math.round(n.domContentLoadedEventEnd) : null, fcp: fcp ? Math.round(fcp.startTime) : null }
  })
  return { loadMs, settleMs, ...nav, ...tally.snapshot() }
}

async function sourceMapCheck (app, image, server) {
  const find = async (argv) => (await execFile('docker', argv)).stdout.split('\n').map((s) => s.trim()).filter(Boolean)
  const inImage = await find(['run', '--rm', '--entrypoint', 'sh', image, '-c', "find / -name '*.mjs.map' 2>/dev/null | head -5"])
  const served = await find(['exec', server.name, 'sh', '-c', "find /usr/share/nginx/html -name '*.mjs.map' 2>/dev/null | head -5"])
  const onDisk = [`${app.dir}/src/main/resources`, `${app.dir}/out`].flatMap((d) => findMap(path.join(ROOT, d)))
  return { inImage, served, bytes: onDisk.length ? statSize(onDisk[0]) : null, onDisk: onDisk.map((p) => path.relative(ROOT, p)) }
}

