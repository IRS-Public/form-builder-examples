#!/usr/bin/env node
//
// perf.mjs — the measurement harness behind the performance audit and its staged plan.
//
// The audit's stages each claim a number. This runs the claim: it measures the same thing twice,
// once against the code as committed at HEAD and once against the working tree, and prints the
// pair. "How much faster" is a ratio or it is an anecdote, so nothing here reports a single figure.
//
//   Stage 1 (DF-3, DF-4, DF-8) — transport. Both sides are throwaway nginx containers started from
//   the app's *already built* runtime image with only /etc/nginx/conf.d/default.conf swapped, so the
//   two sides serve byte-identical files and differ in exactly the thing the stage changed. No sbt
//   run, no image rebuild, nothing written to the repo.
//
//   Two web roots exist and they are not the same site. `--root image` (the default) serves what is
//   baked into the runtime image: the product, built with no developer flags, ~72 subresources.
//   `--root volume` serves the named volume the running stack actually mounts over that path
//   (direct-file_app-out and friends), which the dev overlay's watcher fills with an --auditMode
//   --allScreens --authorMode build — ~148 subresources, and the site the audit's own numbers were
//   taken against. Both are worth knowing; neither is a substitute for the other.
//
//   `site` and `explorer` — the whole plan, end to end. Stages 1 and 2 each isolate one change;
//   these two answer the different question of what a user gets now versus before any of it landed.
//   They need a baseline that is a *built artifact*, not a file swap, because Stage 3 inlines nav
//   templates into generated HTML, Stage 4 changes a library the site is generated by, and Stage 5
//   changes both the vendored bundle and the shape of the data on disk — none of which a running
//   server can be talked into by rewriting a source file. `scripts/perf-baseline.sh` builds that
//   artifact; this script only measures it, and refuses to guess if it is missing.
//
//     site      — the generated Direct File site, pre-plan vs now. Two throwaway nginx containers
//                 from the same runtime image, each with its own nginx.conf and its own web root
//                 bind-mounted over /usr/share/nginx/html. Covers Stage 1 (transport), Stage 3 (the
//                 nav race), Stage 4 (paint before the graph) and Stage 5's TX-3, because all four
//                 land on the same pages.
//     explorer  — Fact Explorer, pre-plan vs now. Two Vite dev servers, each serving its own
//                 checkout and its own generated data. Covers Stage 2 and Stage 5's FX-3/6/7.
//
//   The three repositories are at different points relative to the plan — taxpert and form-builder
//   have committed it, this one has not — so "before" is not one ref. baselineRef() resolves each
//   repo's own: HEAD^ where HEAD is the commit that landed the work, HEAD otherwise. Both sides are
//   printed in the report, because a baseline you cannot name is not a baseline.
//
//   Stage 2 (FX-1, FX-2, FX-4, FX-5) — the Fact Explorer canvas. The dev stack bind-mounts
//   packages/fact-explorer into the Vite container (see taxpert/docker-compose.override.yml), so the
//   baseline side is produced by writing HEAD's copy of the three changed files over the working
//   tree, measuring, and putting the working tree back. That is a real edit to your checkout for the
//   duration of the run: it is guarded by a save-and-verify (contents hashed before, restored and
//   re-hashed after) and by handlers on SIGINT/SIGTERM/uncaughtException, and --no-ab skips it
//   entirely and measures only the working tree.
//
// Preconditions: the full stack is up (`make run-all-docker` here, `make up` in taxpert) and the
// four runtime images exist. Playwright comes from direct-file/node_modules — the smoke test's
// dependency, reused rather than re-declared.
//
// Usage:
//   node scripts/perf.mjs                        # both file-swap stages, both sides
//   node scripts/perf.mjs --stage 1              # one stage
//   scripts/perf-baseline.sh                     # build the pre-plan artifacts (once, ~5 min)
//   node scripts/perf.mjs --stage site,explorer --apps direct-file   # the whole plan, end to end
//   node scripts/perf.mjs --apps direct-file,twe # narrow, like the Makefile's APPS=
//   node scripts/perf.mjs --root volume          # measure the running stack's site, not the image
//   node scripts/perf.mjs --no-ab                # working tree only, no HEAD side
//   node scripts/perf.mjs --json out.json        # machine-readable alongside the report
//
// Timings are loopback and one machine: read the ratios, not the milliseconds. The `cable` profile
// below exists because loopback flatters DF-3 — it moves 12 MB in about a second, which is not what
// that finding is about.

