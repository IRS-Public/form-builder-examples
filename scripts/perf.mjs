function parseArgs (argv) {
  const o = { stages: [1, 2], sides: ['before', 'after'], apps: null, json: null, root: 'image', baseline: DEFAULT_BASELINE }
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]
    // Stages are numbers for the two file-swap stages and names for the two artifact ones; both
    // live in one list so --stage 1,site is a legal and meaningful run.
    if (a === '--stage') o.stages = argv[++i].split(',').map((x) => (/^\d+$/.test(x) ? Number(x) : x))
    else if (a === '--baseline') o.baseline = path.resolve(argv[++i])
    else if (a === '--apps') o.apps = argv[++i].split(',')
    else if (a === '--json') o.json = argv[++i]
    else if (a === '--root') o.root = argv[++i]
    else if (a === '--no-ab') o.sides = ['after']
    else if (a === '--baseline-only') o.sides = ['before']
    else if (a === '-h' || a === '--help') { console.log(readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').filter((l) => l.startsWith('//')).join('\n')); process.exit(0) }
    else fail(`unknown argument: ${a}`)
  }
  return o
}

function gitShow (repo, ref) {
  return execSync(repo, ['git', 'show', ref])
}

function gitRev (repo) {
  try { return execSync(repo, ['git', 'rev-parse', '--short', 'HEAD']).trim() } catch { return '?' }
}

function execSync (cwd, [cmd, ...cmdArgs]) {
  return execFileSync(cmd, cmdArgs, { cwd, encoding: 'utf8', maxBuffer: 1 << 28 })
}

async function curl (url, extra = []) {
  const { stdout } = await execFile('curl', ['-sS', '--max-time', '180', ...extra, url], { maxBuffer: 1 << 28 })
  return stdout
}

