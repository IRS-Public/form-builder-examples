// FX-7 is a header, so it is asked for with curl rather than inferred from a page load: what the
// dev server does with Accept-Encoding, and whether a second visit is a 304 or a re-download.
async function probeGraphTransport (origin, list) {
  const rows = []
  for (const app of list) {
    const url = `${origin}/data/${app.explorer}/form-builder-graph.json`
    const raw = await curl(url, ['-o', '/dev/null', '-D', '-', '-H', 'Accept-Encoding: gzip', '-w', '\n__W %{size_download} %{http_code}\n'])
    const h = Object.fromEntries(raw.split('\n').filter((l) => l.includes(':')).map((l) => [l.slice(0, l.indexOf(':')).trim().toLowerCase(), l.slice(l.indexOf(':') + 1).trim()]))
    const [, wire, code] = raw.match(/__W (\d+) (\d+)/) ?? []
    let revalidated = null
    if (h.etag) {
      const second = await curl(url, ['-o', '/dev/null', '-D', '-', '-H', `If-None-Match: ${h.etag}`, '-w', '\n__W %{size_download} %{http_code}\n'])
      revalidated = Number(second.match(/__W \d+ (\d+)/)?.[1] ?? 0)
    }
    rows.push({ app: app.explorer, status: Number(code), wireBytes: Number(wire), encoding: h['content-encoding'] ?? null, cacheControl: h['cache-control'] ?? null, etag: h.etag ?? null, revalidatedStatus: revalidated })
  }
  return rows
}

async function startVite (dir, tag) {
  const port = 5190 + (tag.includes('before') ? 0 : 1)
  // A stale optimizer cache from a previous run would hide the very thing FX-6 changed, and the two
  // checkouts have different exports maps.
  rmSync(path.join(dir, 'node_modules/.vite'), { recursive: true, force: true })
  const child = spawn('npx', ['vite', '--port', String(port), '--strictPort', '--no-open', '--host', '127.0.0.1'],
    { cwd: dir, env: { ...process.env, VITE_FGM_SOURCE: 'real' }, stdio: ['ignore', 'pipe', 'pipe'] })
  const log = []
  child.stdout.on('data', (b) => log.push(String(b)))
  child.stderr.on('data', (b) => log.push(String(b)))
  const origin = `http://127.0.0.1:${port}`
  for (let i = 0; i < 300; i++) {
    const code = await curl(origin + '/', ['-o', '/dev/null', '-w', '%{http_code}']).catch(() => '')
    if (code === '200') return { origin, stop: async () => { child.kill('SIGTERM'); await sleep(500); child.kill('SIGKILL') } }
    if (child.exitCode !== null) fail(`vite in ${dir} exited ${child.exitCode}:\n${log.join('')}`)
    await sleep(200)
  }
  child.kill('SIGKILL')
  fail(`vite in ${dir} never answered on ${origin}:\n${log.join('')}`)
}

async function measureExplorer (browser, origin, app) {
  const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 } })
  await ctx.addInitScript(instrumentScript())
  const page = await ctx.newPage()
  const t = installNetworkTally(await ctx.newCDPSession(page), origin)
  let wholeGraphFetches = 0
  page.on('request', (r) => { if (/\/data\/.*\/form-builder-graph\.json/.test(r.url())) wholeGraphFetches++ })
  try {
    t.reset()
    const t0 = Date.now()
    await page.goto(`${origin}/fact-explorer/${app.explorer}`, { waitUntil: 'commit', timeout: 300000 })
    await page.waitForSelector('.react-flow__node', { timeout: 300000 })
    const firstNodeMs = Date.now() - t0
    await settleCanvas(page, t0)
    const opening = { firstNodeMs, settleMs: Date.now() - t0, ...t.snapshot(), wholeGraphFetches, ...await canvasCounts(page) }
    const openingFrames = await panFrames(page)

    // The full graph: the one thing the sharding deliberately still supports, and the number that
    // says what it costs when you ask for it.
    let full = null
    let fullFrames = null
    const hasFull = await page.$$eval('#fe-scope option', (els) => els.some((e) => e.value === 'full'))
    if (hasFull) {
      t.reset()
      const t1 = Date.now()
      await page.selectOption('#fe-scope', 'full')
      await settleCanvas(page, t1)
      full = { settleMs: Date.now() - t1, ...t.snapshot(), ...await canvasCounts(page) }
      fullFrames = await panFrames(page)
    }
    return { opening: { ...opening, frames: openingFrames }, full: full && { ...full, frames: fullFrames } }
  } finally {
    await ctx.close()
  }
}

